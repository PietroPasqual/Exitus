type Point = [number, number];

/** Open links and muzzles are positive rim polygons, with genuinely empty centres. */
function rim(cx: number, cy: number, rx: number, ry: number, thickness: number): IntentionPart[] {
  return Array.from({ length: 12 }, (_, i) => {
    const a = i * Math.PI / 6, b = (i + 1) * Math.PI / 6;
    const point = (angle: number, inset: number): Point => [cx + Math.cos(angle) * (rx - inset), cy + Math.sin(angle) * (ry - inset)];
    return part(Math.sin((a + b) / 2) < 0 ? .88 : .36, point(a, 0), point(b, 0), point(b, thickness), point(a, thickness));
  });
}

