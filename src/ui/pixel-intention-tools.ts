/** Positive strips preserve transparent openings, including the one-pixel outline. */
function loop(cx: number, cy: number, rx: number, ry: number, ix: number, iy: number): IntentionPart[] {
  const point = (i: number, x: number, y: number): IntentionPoint => {
    const angle = -Math.PI / 2 + i * Math.PI / 4;
    return [cx + Math.cos(angle) * x, cy + Math.sin(angle) * y];
  };
  return Array.from({ length: 8 }, (_, i) => part(i < 3 ? .88 : i < 6 ? .35 : .69,
    point(i, rx, ry), point(i + 1, rx, ry), point(i + 1, ix, iy), point(i, ix, iy)));
}

