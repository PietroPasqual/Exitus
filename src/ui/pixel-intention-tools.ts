/** Positive strips preserve transparent openings, including the one-pixel outline. */
function loop(cx: number, cy: number, rx: number, ry: number, ix: number, iy: number): IntentionPart[] {
  const point = (i: number, x: number, y: number): IntentionPoint => {
    const angle = -Math.PI / 2 + i * Math.PI / 4;
    return [cx + Math.cos(angle) * x, cy + Math.sin(angle) * y];
  };
  return Array.from({ length: 8 }, (_, i) => {
    const angle = -Math.PI / 2 + (i + .5) * Math.PI / 4;
    const lit = (Math.cos(angle + Math.PI * .72) + 1) / 2;
    const ox = rx - (rx - ix) * .3, oy = ry - (ry - iy) * .3;
    const ax = ix + (rx - ix) * .25, ay = iy + (ry - iy) * .25;
    return [
      part(.27 + lit * .71, point(i, rx, ry), point(i + 1, rx, ry), point(i + 1, ox, oy), point(i, ox, oy)),
      part(.32 + lit * .48, point(i, ox, oy), point(i + 1, ox, oy), point(i + 1, ax, ay), point(i, ax, ay)),
      part(.2 + (1 - lit) * .62, point(i, ax, ay), point(i + 1, ax, ay), point(i + 1, ix, iy), point(i, ix, iy))
    ];
  }).flat();
}

