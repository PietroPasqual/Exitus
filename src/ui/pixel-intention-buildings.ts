import type { IntentionForm } from '../core/intention';
import { part, rect, type IntentionPart, type IntentionPoint } from './pixel-intention-geometry';

function beam(a: IntentionPoint, b: IntentionPoint, width: number, light: number): IntentionPart {
  const length = Math.hypot(b[0] - a[0], b[1] - a[1]);
  const x = -(b[1] - a[1]) / length * width / 2;
  const y = (b[0] - a[0]) / length * width / 2;
  return part(light, [a[0] + x, a[1] + y], [b[0] + x, b[1] + y],
    [b[0] - x, b[1] - y], [a[0] - x, a[1] - y]);
}

/** Rim and spokes are separate strips so the spaces between them stay open. */
function wheel(cx: number, cy: number, radius: number): IntentionPart[] {
  const edge = (angle: number, r: number): IntentionPoint => [cx + Math.cos(angle) * r, cy + Math.sin(angle) * r];
  return [
    ...Array.from({ length: 16 }, (_, i) => {
      const a = i * Math.PI / 8, b = (i + 1) * Math.PI / 8;
      return part(i < 8 ? .42 : .88, edge(a, radius), edge(b, radius), edge(b, radius - 2.3), edge(a, radius - 2.3));
    }),
    ...Array.from({ length: 8 }, (_, i) => beam([cx, cy], edge(i * Math.PI / 4, radius - 1.5), 1.5, i < 4 ? .58 : .86)),
    part(.95, [cx - 2, cy - 2], [cx + 2, cy - 2], [cx + 2, cy + 2], [cx - 2, cy + 2])
  ];
}

