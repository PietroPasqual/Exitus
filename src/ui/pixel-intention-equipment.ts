/** Small open rings are built from strips, so their openings keep the scene behind them. */
function loop(cx: number, cy: number, rx: number, ry: number, thickness: number): IntentionPart[] {
  const result: IntentionPart[] = [];
  for (let i = 0; i < 12; i++) {
    const a = i * Math.PI / 6, b = (i + 1) * Math.PI / 6;
    const p = (angle: number, inset: number): IntentionPoint =>
      [cx + Math.cos(angle) * (rx - inset), cy + Math.sin(angle) * (ry - inset)];
    result.push(part(i < 6 ? .35 : .89, p(a, 0), p(b, 0), p(b, thickness), p(a, thickness)));
  }
  return result;
}

