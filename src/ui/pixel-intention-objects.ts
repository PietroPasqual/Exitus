const polygon = (cx: number, cy: number, rx: number, ry: number, count: number, phase = 0): IntentionPoint[] =>
  Array.from({ length: count }, (_, i) => {
    const angle = phase + i / count * Math.PI * 2;
    return [cx + Math.cos(angle) * rx, cy + Math.sin(angle) * ry];
  });

/** Separate quads leave the central opening genuinely unpainted. */
function ring(cx: number, cy: number, outerX: number, outerY: number, innerX: number, innerY: number): IntentionPart[] {
  const outer = polygon(cx, cy, outerX, outerY, 16, -Math.PI / 2);
  const rim = polygon(cx, cy, outerX - (outerX - innerX) * .23, outerY - (outerY - innerY) * .23, 16, -Math.PI / 2);
  const inset = polygon(cx, cy, innerX + (outerX - innerX) * .28, innerY + (outerY - innerY) * .28, 16, -Math.PI / 2);
  const inner = polygon(cx, cy, innerX, innerY, 16, -Math.PI / 2);
  return outer.flatMap((point, i) => {
    const next = (i + 1) % outer.length;
    const angle = -Math.PI / 2 + (i + .5) / 16 * Math.PI * 2;
    const lit = (Math.cos(angle + Math.PI * .72) + 1) / 2;
    // Three positive strips make a rounded outer rim and an opposing inner bevel.
    return [
      part(.25 + lit * .73, point, outer[next], rim[next], rim[i]),
      part(.32 + lit * .49, rim[i], rim[next], inset[next], inset[i]),
      part(.19 + (1 - lit) * .64, inset[i], inset[next], inner[next], inner[i])
    ];
  });
}

function spiral(): IntentionPart[] {
  const points = Array.from({ length: 65 }, (_, i) => {
    const t = i / 64, angle = -Math.PI / 2 + t * Math.PI * 4;
    const radius = 4 + t * 13;
    return { angle, radius };
  });
  const edge = (at: typeof points[number], side: number): IntentionPoint =>
    [Math.cos(at.angle) * (at.radius + side * 1.7), Math.sin(at.angle) * (at.radius + side * 1.7)];
  return points.slice(0, -1).flatMap((point, i) => {
    const next = points[i + 1];
    const lit = (Math.cos(point.angle + Math.PI * .72) + 1) / 2;
    // A continuous, carved ribbon has a raised crest and a shadowed inner edge.
    return [
      part(.22 + lit * .34, edge(point, -1), edge(point, -.22), edge(next, -.22), edge(next, -1)),
      part(.62 + lit * .36, edge(point, -.22), edge(point, .4), edge(next, .4), edge(next, -.22)),
      part(.25 + lit * .48, edge(point, .4), edge(point, 1), edge(next, 1), edge(next, .4))
    ];
  });
}

const star = Array.from({ length: 10 }, (_, i): IntentionPoint => {
  const angle = -Math.PI / 2 + i * Math.PI / 5, radius = i % 2 ? 8 : 19;
  return [Math.cos(angle) * radius, Math.sin(angle) * radius];
});
const blast = Array.from({ length: 24 }, (_, i): IntentionPoint => {
  const angle = -Math.PI / 2 + i * Math.PI / 12;
  const radius = i % 2 ? 7 : [19, 15, 18, 17, 19, 15][(i / 2) % 6];
  return [Math.cos(angle) * radius, Math.sin(angle) * radius];
});

